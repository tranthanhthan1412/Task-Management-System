import { fileURLToPath } from "node:url";
import { randomBytes } from "node:crypto";
import mongoose from "mongoose";
import { MongoMemoryServer } from "mongodb-memory-server";
process.env.NODE_ENV = "test";
process.env.JWT_SECRET = randomBytes(48).toString("hex");
process.env.CLIENT_URL = "http://localhost:5174";
process.env.PORT = "5002";
process.env.API_PUBLIC_URL = "http://localhost:5002";
process.env.COOKIE_SECURE = "false";
process.env.TRUST_PROXY_HOPS = "0";
process.env.JWT_EXPIRES_IN = "7d";
const mongo = await MongoMemoryServer.create({ binary: { downloadDir: fileURLToPath(new URL("../node_modules/.cache/mongodb-memory-server", import.meta.url)) } });
await mongoose.connect(mongo.getUri(), { dbName: "taskpilot_e2e" });
const { app } = await import("../src/app.js");
const { default: User } = await import("../src/models/User.js");
const { default: Session } = await import("../src/models/Session.js");
const { default: Task } = await import("../src/models/Task.js");
await Promise.all([User.init(), Session.init(), Task.init()]);
const server = app.listen(5002, "127.0.0.1", () => console.log("E2E API ready"));
const stop = async () => { server.close(); await mongoose.disconnect(); await mongo.stop(); process.exit(0); };
process.on("SIGINT", stop); process.on("SIGTERM", stop);
